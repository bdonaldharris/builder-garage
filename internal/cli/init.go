// isInteractive reports whether both input and output are terminals. A
// terminal is approximated portably as a character device other than the
// null device.
func isInteractive(in io.Reader, out io.Writer) bool {
	inFile, ok := in.(*os.File)
	if !ok {
		return false
	}
	outFile, ok := out.(*os.File)
	if !ok {
		return false
	}
	for _, f := range []*os.File{inFile, outFile} {
		info, err := f.Stat()
		if err != nil || info.Mode()&fs.ModeCharDevice == 0 {
			return false
		}
		if null, err := os.Stat(os.DevNull); err == nil && os.SameFile(info, null) {
			return false
		}
	}
	return true
}

func reportInit(w io.Writer, projectDir string, result initResult) error {
	configRel := filepath.Join(garageDirName, configFileName)
	var msg string
	switch result.Action {
	case initCreated:
		msg = fmt.Sprintf("Initialized Builder Garage in %s\n  created %s (schema version %d)\n",
			projectDir, configRel, configSchemaVersion)
	case initUpgraded:
		msg = fmt.Sprintf("Updated Builder Garage configuration in %s\n  upgraded %s from schema version %d to %d\n",
			projectDir, configRel, result.FromVersion, configSchemaVersion)
	case initUpdated:
		msg = fmt.Sprintf("Updated Builder Garage configuration in %s\n  added to %s: %s\n",
			projectDir, configRel, strings.Join(result.Added, ", "))
	default:
		msg = fmt.Sprintf("Builder Garage configuration in %s is up to date\n  %s was not changed\n",
			projectDir, configRel)
	}
	_, err := io.WriteString(w, msg+"Check it with \"garage config validate\".\n")
	return err
}

// configFromFlags builds the configuration the flags ask for. Only settings
// whose flags were given are set.
func configFromFlags(f initFlags, changed func(string) bool) (projectConfig, error) {
	cfg := projectConfig{SchemaVersion: configSchemaVersion, Project: &projectChoices{}}
	pc := cfg.Project
	var errs []string
	fail := func(format string, args ...any) { errs = append(errs, fmt.Sprintf(format, args...)) }

	if changed("integration-branch") {
		pc.IntegrationBranch = &f.IntegrationBranch
	}
	if changed("pr-review-trigger") {
		list := make([]namedCondition, 0, len(f.PRReviewTriggers))
		for _, v := range f.PRReviewTriggers {
			c, err := parseNamedCondition(v)
			if err != nil {
				fail("--pr-review-trigger %q: %v", v, err)
			}
			list = append(list, c)
		}
		pc.PRReviewTriggers = &list
	}
	if changed("automated-reviewer") || changed("automated-reviewer-request") {
		pc.AutomatedReviewer = &automatedReviewer{Name: f.AutomatedReviewer, Request: f.AutomatedReviewerRequest}
	}
	if changed("small-corrections") || changed("small-corrections-without-issue") {
		sc := &smallCorrections{}
		switch f.SmallCorrections {
		case "enabled":
			sc.Enabled = boolPtr(true)
		case "disabled":
			sc.Enabled = boolPtr(false)
		case "":
			if changed("small-corrections") {
				fail("--small-corrections must be enabled or disabled")
			}
		default:
			fail("--small-corrections must be enabled or disabled, not %q", f.SmallCorrections)
		}
		if changed("small-corrections-without-issue") {
			sc.WithoutIssue = boolPtr(f.SmallCorrectionsWithoutIssue)
		}
		pc.SmallCorrections = sc
	}
	if changed("discovery") || changed("discovery-trigger") {
		d := &discoveryChoice{Mode: f.Discovery}
		if changed("discovery-trigger") {
			list := make([]namedCondition, 0, len(f.DiscoveryTriggers))
			for _, v := range f.DiscoveryTriggers {
				c, err := parseNamedCondition(v)
				if err != nil {
					fail("--discovery-trigger %q: %v", v, err)
				}
				list = append(list, c)
			}
			d.Triggers = &list
		}
		pc.Discovery = d
	}
	if changed("release-condition") {
		list := make([]releaseCond, 0, len(f.ReleaseConditions))
		for _, v := range f.ReleaseConditions {
			c, err := parseReleaseCondition(v)
			if err != nil {
				fail("--release-condition %q: %v", v, err)
			}
			list = append(list, c)
		}
		pc.ReleaseConditions = &list
	}
	if changed("suggestions-backlog") {
		pc.SuggestionsBacklog = &f.SuggestionsBacklog
	}
	authorityFlags := []struct {
		name  string
		value string
		set   func(*authorities, *authority)
	}{
		{"workflow-owner", f.WorkflowOwner, func(a *authorities, v *authority) { a.WorkflowOwner = v }},
		{"change-acceptor", f.ChangeAcceptor, func(a *authorities, v *authority) { a.ChangeAcceptor = v }},
		{"product-intent-acceptor", f.ProductIntentAcceptor, func(a *authorities, v *authority) { a.ProductIntentAcceptor = v }},
		{"small-correction-classifier", f.SmallCorrectionClassifier, func(a *authorities, v *authority) { a.SmallCorrectionClassifier = v }},
	}
	for _, af := range authorityFlags {
		if !changed(af.name) {
			continue
		}
		if pc.Authorities == nil {
			pc.Authorities = &authorities{}
		}
		a := parseAuthority(af.value)
		af.set(pc.Authorities, &a)
	}
	if changed("inspection-condition") {
		pc.UserFacingInspection = &inspectionChoice{AdditionalConditions: nonEmpty(f.InspectionConditions)}
	}
	if changed("manual") || changed("conditional-guidance") {
		g := &guidanceChoice{Conditional: nonEmpty(f.ConditionalGuidance)}
		for _, v := range f.Manuals {
			m, err := parseManual(v)
			if err != nil {
				fail("--manual %q: %v", v, err)
			}
			g.Manuals = append(g.Manuals, m)
		}
		pc.Guidance = g
	}
	if changed("skill-target") {
		list := make([]skillTarget, 0, len(f.SkillTargets))
		for _, v := range f.SkillTargets {
			t, err := parseSkillTarget(v)
			if err != nil {
				fail("--skill-target %q: %v", v, err)
			}
			list = append(list, t)
		}
		cfg.Tooling = &toolingConfig{SkillTargets: &list}
	}

	if len(errs) > 0 {
		return projectConfig{}, errors.New(strings.Join(errs, "\n"))
	}
	return cfg, nil
}

func boolPtr(v bool) *bool { return &v }

// nonEmpty returns nil for an empty list, so an unset list and an empty one
// are represented identically and encode the same way.
func nonEmpty(values []string) []string {
	if len(values) == 0 {
		return nil
	}
	return values
}

func parseNamedCondition(v string) (namedCondition, error) {
	name, when, ok := strings.Cut(v, "|")
	name, when = strings.TrimSpace(name), strings.TrimSpace(when)
	if !ok || name == "" || when == "" {
		return namedCondition{}, errors.New("want NAME|WHEN IT APPLIES")
	}
	return namedCondition{Name: name, AppliesWhen: when}, nil
}

func parseReleaseCondition(v string) (releaseCond, error) {
	parts := strings.Split(v, "|")
	if len(parts) != 3 {
		return releaseCond{}, errors.New("want NAME|WHEN IT APPLIES|EVIDENCE IT REQUIRES")
	}
	c := releaseCond{
		Name:             strings.TrimSpace(parts[0]),
		AppliesWhen:      strings.TrimSpace(parts[1]),
		RequiredEvidence: strings.TrimSpace(parts[2]),
	}
	if c.Name == "" || c.AppliesWhen == "" || c.RequiredEvidence == "" {
		return releaseCond{}, errors.New("want NAME|WHEN IT APPLIES|EVIDENCE IT REQUIRES")
	}
	return c, nil
}

func parseAuthority(v string) authority {
	role, members, _ := strings.Cut(v, ":")
	a := authority{Role: strings.TrimSpace(role)}
	for _, m := range strings.Split(members, ",") {
		if m = strings.TrimSpace(m); m != "" {
			a.Members = append(a.Members, m)
		}
	}
	return a
}

func parseManual(v string) (manualChoice, error) {
	i := strings.LastIndex(v, "@")
	if i <= 0 || i == len(v)-1 {
		return manualChoice{}, errors.New("want NAME@VERSION")
	}
	return manualChoice{Name: strings.TrimSpace(v[:i]), Version: strings.TrimSpace(v[i+1:])}, nil
}

func parseSkillTarget(v string) (skillTarget, error) {
	parts := strings.Split(v, "@")
	if len(parts) != 3 {
		return skillTarget{}, errors.New("want HARNESS@VERSION@YYYY-MM-DD")
	}
	harness := strings.TrimSpace(parts[0])
	rule, ok := supportedSkillTargets[harness]
	if !ok {
		return skillTarget{}, fmt.Errorf("harness must be one of %s", strings.Join(supportedHarnesses, ", "))
	}
	return skillTarget{
		Harness:          harness,
		Scope:            scopeUser,
		Path:             rule,
		ConfirmedVersion: strings.TrimSpace(parts[1]),
		ConfirmedOn:      strings.TrimSpace(parts[2]),
	}, nil
}

// configSetting is one independently configurable setting: an extension
// point, one E8 responsibility, or a tooling setting. A setting is the unit
// init adds, and the unit it refuses to change.
type configSetting struct {
	path []string
	get  func(*projectConfig) any // nil when the setting is absent
	set  func(dst, src *projectConfig)
}

func projectOf(c *projectConfig) *projectChoices {
	if c.Project == nil {
		c.Project = &projectChoices{}
	}
	return c.Project
}

func authoritiesOf(c *projectConfig) *authorities {
	pc := projectOf(c)
	if pc.Authorities == nil {
		pc.Authorities = &authorities{}
	}
	return pc.Authorities
}

// proj and auths read a section without creating it.
func proj(c *projectConfig) *projectChoices {
	if c.Project == nil {
		return &projectChoices{}
	}
	return c.Project
}

func auths(c *projectConfig) *authorities {
	if pc := proj(c); pc.Authorities != nil {
		return pc.Authorities
	}
	return &authorities{}
}

func present[T any](v *T) any {
	if v == nil {
		return nil
	}
	return v
}

