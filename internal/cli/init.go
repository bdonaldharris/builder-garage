func settingName(path []string) string { return strings.Join(path, ".") }

// mergeSettings adds to base every setting of desired that base lacks. A
// setting both define with different values is a conflict; base is never
// changed for it.
func mergeSettings(base *projectConfig, desired projectConfig) (added [][]string, conflicts []string) {
	for _, s := range configSettings {
		want := s.get(&desired)
		if want == nil {
			continue
		}
		have := s.get(base)
		switch {
		case have == nil:
			s.set(base, &desired)
			added = append(added, s.path)
		case !reflect.DeepEqual(have, want):
			conflicts = append(conflicts, settingName(s.path))
		}
	}
	return added, conflicts
}

// requiredPrompt asks for one required value that is still missing.
type requiredPrompt struct {
	flag     string
	question string
	missing  func(*projectConfig) bool
	ask      func(prompter, *projectConfig) error
}

func askAuthority(question string, set func(*authorities, *authority)) func(prompter, *projectConfig) error {
	return func(p prompter, c *projectConfig) error {
		for {
			answer, err := p.Ask(question)
			if err != nil {
				return err
			}
			if a := parseAuthority(answer); a.Role != "" {
				set(authoritiesOf(c), &a)
				return nil
			}
		}
	}
}

func smallCorrectionsEnabled(c *projectConfig) bool {
	sc := proj(c).SmallCorrections
	return sc != nil && sc.Enabled != nil && *sc.Enabled
}

var requiredPrompts = []requiredPrompt{
	{
		flag: "--discovery",
		missing: func(c *projectConfig) bool {
			return proj(c).Discovery == nil
		},
		ask: func(p prompter, c *projectConfig) error {
			for {
				mode, err := p.Ask("Discovery applicability (E5), " + strings.Join(discoveryModes, " or ") + ": ")
				if err != nil {
					return err
				}
				switch mode {
				case discoveryJudgment:
					projectOf(c).Discovery = &discoveryChoice{Mode: mode}
					return nil
				case discoveryTriggers:
					var list []namedCondition
					for {
						answer, err := p.Ask("  Discovery trigger as NAME|WHEN (empty to finish): ")
						if err != nil {
							return err
						}
						if answer == "" {
							if len(list) > 0 {
								break
							}
							continue
						}
						if t, err := parseNamedCondition(answer); err == nil {
							list = append(list, t)
						}
					}
					projectOf(c).Discovery = &discoveryChoice{Mode: mode, Triggers: &list}
					return nil
				}
			}
		},
	},
	{
		flag:    "--workflow-owner",
		missing: func(c *projectConfig) bool { return auths(c).WorkflowOwner == nil },
		ask: askAuthority("Workflow Owner (E8), as ROLE or ROLE:MEMBERS: ",
			func(a *authorities, v *authority) { a.WorkflowOwner = v }),
	},
	{
		flag:    "--change-acceptor",
		missing: func(c *projectConfig) bool { return auths(c).ChangeAcceptor == nil },
		ask: askAuthority("Change acceptor (E8), as ROLE or ROLE:MEMBERS: ",
			func(a *authorities, v *authority) { a.ChangeAcceptor = v }),
	},
	{
		flag:    "--product-intent-acceptor",
		missing: func(c *projectConfig) bool { return auths(c).ProductIntentAcceptor == nil },
		ask: askAuthority("Product-intent acceptor (E8), as ROLE or ROLE:MEMBERS: ",
			func(a *authorities, v *authority) { a.ProductIntentAcceptor = v }),
	},
	{
		flag: "--small-correction-classifier",
		missing: func(c *projectConfig) bool {
			return smallCorrectionsEnabled(c) && auths(c).SmallCorrectionClassifier == nil
		},
		ask: askAuthority("Small-correction classifier (E8), as ROLE or ROLE:MEMBERS: ",
			func(a *authorities, v *authority) { a.SmallCorrectionClassifier = v }),
	},
}

// fillRequired prompts for each required value that is still missing, or,
// without a prompter, reports every missing value as one error.
func fillRequired(cfg *projectConfig, ask prompter) ([][]string, error) {
	var added [][]string
	var missing []string
	for _, r := range requiredPrompts {
		if !r.missing(cfg) {
			continue
		}
		if ask == nil {
			missing = append(missing, r.flag)
			continue
		}
		if err := r.ask(ask, cfg); err != nil {
			return nil, err
		}
		added = append(added, promptedPath(r.flag))
	}
	if len(missing) > 0 {
		return nil, fmt.Errorf("%w: supply %s, or run \"garage init\" in an interactive terminal; nothing was written",
			errMissingRequired, strings.Join(missing, ", "))
	}
	return added, nil
}

func promptedPath(flag string) []string {
	switch flag {
	case "--discovery":
		return []string{"project", "discovery"}
	case "--workflow-owner":
		return []string{"project", "authorities", "workflow_owner"}
	case "--change-acceptor":
		return []string{"project", "authorities", "change_acceptor"}
	case "--product-intent-acceptor":
		return []string{"project", "authorities", "product_intent_acceptor"}
	default:
		return []string{"project", "authorities", "small_correction_classifier"}
	}
}

// initProject creates or upgrades the configuration in projectDir. A new or
// upgraded configuration is written only after it validates, so init never
// leaves an invalid or incomplete configuration, and never changes an
// existing value. ask may be nil, in which case no value is prompted for.
//
// The implementation repeats path and directory-identity checks around
// sensitive operations, but Go's portable path-based filesystem APIs cannot
// eliminate every race with a hostile process concurrently replacing parent
// directory entries. An existing destination is never opened for writing: a
// completed same-directory temporary file replaces its directory entry.
func initProject(projectDir string, desired projectConfig, ask prompter) (initResult, error) {
	garageDir := filepath.Join(projectDir, garageDirName)
	configPath := filepath.Join(garageDir, configFileName)

	exists := false
	if _, err := os.Lstat(garageDir); err == nil {
		if _, err := ensureGarageDirectory(garageDir); err != nil {
			return initResult{}, err
		}
		if exists, err = inspectConfigDestination(configPath); err != nil {
			return initResult{}, err
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return initResult{}, fmt.Errorf("cannot inspect the %s directory: %w", garageDirName, err)
	}

	if !exists {
		return createNewConfig(garageDir, configPath, desired, ask)
	}
	return upgradeConfig(garageDir, configPath, desired, ask)
}

func createNewConfig(garageDir, configPath string, desired projectConfig, ask prompter) (initResult, error) {
	cfg := projectConfig{SchemaVersion: configSchemaVersion}
	if _, conflicts := mergeSettings(&cfg, desired); len(conflicts) > 0 {
		return initResult{}, fmt.Errorf("conflicting values for %s", strings.Join(conflicts, ", "))
	}
	if problems := validateConfig(withoutMissingRequired(cfg)); problems != nil {
		return initResult{}, fmt.Errorf("%w; nothing was written", problems)
	}
	if _, err := fillRequired(&cfg, ask); err != nil {
		return initResult{}, err
	}
	if problems := validateConfig(cfg); problems != nil {
		return initResult{}, fmt.Errorf("%w; nothing was written", problems)
	}
	content, err := renderNewConfig(cfg)
	if err != nil {
		return initResult{}, err
	}

	garageInfo, err := ensureGarageDirectory(garageDir)
	if err != nil {
		return initResult{}, err
	}
	if err := createConfigurationExclusive(configPath, content, garageDir, garageInfo); err != nil {
		return initResult{}, err
	}
	return initResult{Action: initCreated}, nil
}

func upgradeConfig(garageDir, configPath string, desired projectConfig, ask prompter) (initResult, error) {
	stop := func(format string, args ...any) (initResult, error) {
		return initResult{}, fmt.Errorf("%s was not changed: %s", configPath, fmt.Sprintf(format, args...))
	}

	data, err := readConfigFile(configPath)
	if err != nil {
		return initResult{}, err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return stop("it is not valid YAML (%v); correct it by hand, then run \"garage init\" again", err)
	}
	existing, err := decodeConfig(data)
	if err != nil {
		return stop("it does not match the configuration schema (%v); correct it by hand, then run \"garage init\" again", err)
	}
	if doc.Kind != yaml.DocumentNode || len(doc.Content) != 1 || doc.Content[0].Kind != yaml.MappingNode {
		return stop("it is not a YAML mapping; correct it by hand, then run \"garage init\" again")
	}

	fromVersion := existing.SchemaVersion
	switch fromVersion {
	case configSchemaVersion:
	case 1:
		// A version 1 file records only its schema version. Anything else in
		// it makes the migration ambiguous.
		if existing.Project != nil || existing.Tooling != nil || len(doc.Content[0].Content) != 2 {
			return stop("a schema version 1 file must contain only schema_version; remove the other keys by hand, then run \"garage init\" again")
		}
		existing.SchemaVersion = configSchemaVersion
	default:
		return stop("schema version %d is not supported by this garage; it supports versions 1 and %d", fromVersion, configSchemaVersion)
	}

	merged := existing
	merged.Project = cloneProject(existing.Project)
	merged.Tooling = cloneTooling(existing.Tooling)
	added, conflicts := mergeSettings(&merged, desired)
	if len(conflicts) > 0 {
		return stop("these settings are already configured with different values: %s; change configured values through the project's normal review process, not with init",
			strings.Join(conflicts, ", "))
	}
	if problems := validateConfig(withoutMissingRequired(merged)); problems != nil {
		return stop("%v\nCorrect it by hand, then run \"garage init\" again", problems)
	}
	prompted, err := fillRequired(&merged, ask)
	if err != nil {
		return initResult{}, err
	}
	added = append(added, prompted...)
	if problems := validateConfig(merged); problems != nil {
		return stop("%v", problems)
	}

	if fromVersion == configSchemaVersion && len(added) == 0 {
		return initResult{Action: initUnchanged}, nil
	}

	if err := applyToDocument(&doc, merged, added, fromVersion != configSchemaVersion); err != nil {
		return initResult{}, err
	}
	content, err := encodeDocument(&doc)
	if err != nil {
		return initResult{}, err
	}
	// The written file must decode to exactly the validated configuration.
	if check, err := decodeConfig(content); err != nil || !reflect.DeepEqual(check, merged) {
		return initResult{}, fmt.Errorf("internal error: the upgraded configuration did not round-trip; %s was not changed", configPath)
	}

	garageInfo, err := ensureGarageDirectory(garageDir)
	if err != nil {
		return initResult{}, err
	}
	if err := replaceConfiguration(configPath, content, garageInfo, prepareTemporaryConfig, commitConfigReplacement); err != nil {
		return initResult{}, err
	}

	if fromVersion != configSchemaVersion {
		return initResult{Action: initUpgraded, FromVersion: fromVersion}, nil
	}
	names := make([]string, 0, len(added))
	for _, path := range added {
		names = append(names, settingName(path))
	}
	return initResult{Action: initUpdated, Added: names}, nil
}

// withoutMissingRequired fills every missing required value with a
// placeholder, so validation reports only problems with the values present.
func withoutMissingRequired(cfg projectConfig) projectConfig {
	probe := cfg
	probe.Project = cloneProject(cfg.Project)
	placeholder := &authority{Role: "placeholder"}
	pc := projectOf(&probe)
	if pc.Discovery == nil {
		pc.Discovery = &discoveryChoice{Mode: discoveryJudgment}
	}
	a := authoritiesOf(&probe)
	if a.WorkflowOwner == nil {
		a.WorkflowOwner = placeholder
	}
	if a.ChangeAcceptor == nil {
		a.ChangeAcceptor = placeholder
	}
	if a.ProductIntentAcceptor == nil {
		a.ProductIntentAcceptor = placeholder
	}
	if smallCorrectionsEnabled(&probe) && a.SmallCorrectionClassifier == nil {
		a.SmallCorrectionClassifier = placeholder
	}
	return probe
}

func cloneProject(pc *projectChoices) *projectChoices {
	if pc == nil {
		return nil
	}
	c := *pc
	if pc.Authorities != nil {
		a := *pc.Authorities
		c.Authorities = &a
	}
	return &c
}

func cloneTooling(t *toolingConfig) *toolingConfig {
	if t == nil {
		return nil
	}
	c := *t
	return &c
}

// applyToDocument adds each added setting to doc, keeping every existing node
// and comment. When migrate is true, it also sets schema_version.
func applyToDocument(doc *yaml.Node, cfg projectConfig, added [][]string, migrate bool) error {
	root := doc.Content[0]
	if migrate {
		version := mappingValue(root, "schema_version")
		if version == nil || version.Kind != yaml.ScalarNode {
			return errors.New("internal error: schema_version is missing")
		}
		version.Value = fmt.Sprint(configSchemaVersion)
		version.Tag = "!!int"
	}
	for _, path := range added {
		value := settingByPath(path).get(&cfg)
		if err := addToMapping(root, path, value); err != nil {
			return err
		}
	}
	return nil
}

func settingByPath(path []string) configSetting {
	for _, s := range configSettings {
		if slicesEqual(s.path, path) {
			return s
		}
	}
	panic("unknown configuration setting " + settingName(path))
}

func slicesEqual(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

func mappingValue(m *yaml.Node, key string) *yaml.Node {
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}

// addToMapping adds value at path inside the mapping m, creating
// intermediate mappings. It never replaces an existing key.
func addToMapping(m *yaml.Node, path []string, value any) error {
	for i, key := range path {
		existing := mappingValue(m, key)
		if i == len(path)-1 {
			if existing != nil {
				return fmt.Errorf("internal error: %s already exists", settingName(path))
			}
			var v yaml.Node
			if err := v.Encode(value); err != nil {
				return fmt.Errorf("cannot encode %s: %w", settingName(path), err)
			}
			m.Style = 0
			m.Content = append(m.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: key}, &v)
			return nil
		}
		if existing == nil {
			existing = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
			m.Style = 0
			m.Content = append(m.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: key}, existing)
		}
		if existing.Kind != yaml.MappingNode {
			return fmt.Errorf("%s is not a mapping", settingName(path[:i+1]))
		}
		m = existing
	}
	return nil
}

func encodeDocument(doc *yaml.Node) ([]byte, error) {
	var buf bytes.Buffer
	encoder := yaml.NewEncoder(&buf)
	encoder.SetIndent(2)
	if err := encoder.Encode(doc); err != nil {
		return nil, fmt.Errorf("cannot encode the configuration: %w", err)
	}
	if err := encoder.Close(); err != nil {
		return nil, fmt.Errorf("cannot encode the configuration: %w", err)
	}
	return buf.Bytes(), nil
}

// renderNewConfig returns the content of a new configuration file.
func renderNewConfig(cfg projectConfig) ([]byte, error) {
	var doc yaml.Node
	if err := doc.Encode(cfg); err != nil {
		return nil, fmt.Errorf("cannot encode the configuration: %w", err)
	}
	body, err := encodeDocument(&yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{&doc}})
	if err != nil {
		return nil, err
	}
	content := append([]byte(configHeader), body...)
	if check, err := decodeConfig(content); err != nil || !reflect.DeepEqual(check, cfg) {
		return nil, errors.New("internal error: the new configuration did not round-trip")
	}
	return content, nil
}

func ensureGarageDirectory(garageDir string) (fs.FileInfo, error) {
	info, err := os.Lstat(garageDir)
	if errors.Is(err, fs.ErrNotExist) {
		if err := os.Mkdir(garageDir, 0o755); err != nil {
			if !errors.Is(err, fs.ErrExist) {
				return nil, fmt.Errorf("cannot create the %s directory: %w", garageDirName, err)
			}
		}
		info, err = os.Lstat(garageDir)
	}
	if err != nil {
		return nil, fmt.Errorf("cannot inspect the %s directory: %w", garageDirName, err)
	}
	if info.Mode()&fs.ModeSymlink != 0 {
		return nil, fmt.Errorf("refusing to use %s: the directory is a symbolic link", garageDir)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("cannot create the %s directory: %s already exists and is not a directory",
			garageDirName, garageDir)
	}
	return info, nil
}

func verifyGarageDirectory(garageDir string, expected fs.FileInfo) error {
	current, err := os.Lstat(garageDir)
	if err != nil {
		return fmt.Errorf("cannot verify the %s directory: %w", garageDirName, err)
	}
	if current.Mode()&fs.ModeSymlink != 0 || !current.IsDir() || !os.SameFile(expected, current) {
		return fmt.Errorf("refusing to write configuration: the %s directory changed during initialization",
			garageDirName)
	}
	return nil
}

func inspectConfigDestination(configPath string) (bool, error) {
	info, err := os.Lstat(configPath)
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, fmt.Errorf("cannot inspect the configuration destination: %w", err)
	}
	if info.Mode()&fs.ModeSymlink != 0 {
		return false, fmt.Errorf(
			"refusing to write configuration: %s is a symbolic link; remove it and retry",
			configPath,
		)
	}
	if !info.Mode().IsRegular() {
		return false, fmt.Errorf(
			"refusing to write configuration: %s is not a regular file (%s); remove it and retry",
			configPath,
			info.Mode().Type(),
		)
	}
	return true, nil
}

func configExistsError(configPath string) error {
	return fmt.Errorf("%w: %s appeared while it was being created and was left unchanged; run \"garage init\" again to upgrade it",
		errConfigExists, configPath)
}

func createConfigurationExclusive(
	configPath string,
	content []byte,
	garageDir string,
	garageInfo fs.FileInfo,
) error {
	if err := verifyGarageDirectory(garageDir, garageInfo); err != nil {
		return err
	}

	// O_EXCL preserves ordinary initialization's create-only contract and, in
	// combination with O_CREATE, does not follow a final-component symlink.
	file, err := os.OpenFile(configPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		if errors.Is(err, fs.ErrExist) {
			exists, inspectErr := inspectConfigDestination(configPath)
			if inspectErr != nil {
				return inspectErr
			}
			if exists {
				return configExistsError(configPath)
			}
		}
		return fmt.Errorf("cannot create the configuration file: %w", err)
	}

	createdInfo, statErr := file.Stat()
	if statErr != nil {
		_ = file.Close()
		return fmt.Errorf("cannot inspect the new configuration file: %w", statErr)
	}

	if err := verifyGarageDirectory(garageDir, garageInfo); err != nil {
		_ = file.Close()
		removeIfSameFile(configPath, createdInfo)
		return err
	}

	_, writeErr := file.Write(content)
	syncErr := file.Sync()
	closeErr := file.Close()
	if err := errors.Join(writeErr, syncErr, closeErr); err != nil {
		removeIfSameFile(configPath, createdInfo)
		return fmt.Errorf("cannot write the configuration file: %w", err)
	}
	return nil
}

type temporaryConfigPreparer func(string, []byte) (string, error)
type configReplacementCommitter func(string, string) error

func replaceConfiguration(
	configPath string,
	content []byte,
	garageInfo fs.FileInfo,
	prepare temporaryConfigPreparer,
	commit configReplacementCommitter,
) error {
	garageDir := filepath.Dir(configPath)
	if err := verifyGarageDirectory(garageDir, garageInfo); err != nil {
		return err
	}

	tempPath, err := prepare(garageDir, content)
	if err != nil {
		return fmt.Errorf("cannot prepare the replacement configuration: %w", err)
	}
	committed := false
	defer func() {
		if !committed {
			_ = os.Remove(tempPath)
		}
	}()

	if err := verifyGarageDirectory(garageDir, garageInfo); err != nil {
		return err
	}
	if _, err := inspectConfigDestination(configPath); err != nil {
		return err
	}
	if err := commit(tempPath, configPath); err != nil {
		return fmt.Errorf("cannot replace the configuration file: %w", err)
	}
	committed = true
	return nil
}

func prepareTemporaryConfig(garageDir string, content []byte) (string, error) {
	return prepareTemporaryConfigUsing(garageDir, content, writeTemporaryConfig)
}

func prepareTemporaryConfigUsing(
	garageDir string,
	content []byte,
	write func(*os.File, []byte) error,
) (string, error) {
	file, err := os.CreateTemp(garageDir, "."+configFileName+".tmp-*")
	if err != nil {
		return "", err
	}
	path := file.Name()
	keep := false
	defer func() {
		if !keep {
			_ = file.Close()
			_ = os.Remove(path)
		}
	}()

	if err := write(file, content); err != nil {
		return "", err
	}
	keep = true
	return path, nil
}

func writeTemporaryConfig(file *os.File, content []byte) error {
	_, writeErr := file.Write(content)
	chmodErr := file.Chmod(0o644)
	syncErr := file.Sync()
	closeErr := file.Close()
	return errors.Join(writeErr, chmodErr, syncErr, closeErr)
}

func removeIfSameFile(path string, expected fs.FileInfo) {
	if expected == nil {
		return
	}
	current, err := os.Lstat(path)
	if err != nil || current.Mode()&fs.ModeSymlink != 0 {
		return
	}
	if os.SameFile(expected, current) {
		_ = os.Remove(path)
	}
}
