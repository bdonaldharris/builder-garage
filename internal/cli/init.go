// initAction is what "garage init" did to the configuration file.
type initAction int

const (
	initCreated initAction = iota
	initUpgraded
	initUpdated
	initUnchanged
)

// initResult describes a completed initialization.
type initResult struct {
	Action      initAction
	FromVersion int
	Added       []string
}

// prompter asks for a required value in an interactive terminal.
type prompter interface {
	Ask(question string) (string, error)
}

type linePrompter struct {
	in  *bufio.Reader
	out io.Writer
}

func (p linePrompter) Ask(question string) (string, error) {
	if _, err := fmt.Fprint(p.out, question); err != nil {
		return "", err
	}
	line, err := p.in.ReadString('\n')
	if err != nil && !(errors.Is(err, io.EOF) && line != "") {
		if errors.Is(err, io.EOF) {
			return "", errors.New("input ended before every required value was supplied")
		}
		return "", err
	}
	return strings.TrimSpace(line), nil
}

